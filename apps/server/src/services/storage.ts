import { GetObjectCommand, PutObjectCommand, S3Client } from '@aws-sdk/client-s3';
import crypto from 'node:crypto';
import fs from 'node:fs/promises';
import path from 'node:path';
import { config } from '../config';

/**
 * Storage for original uploads. Files are stored under random names with no
 * extension and are only ever served back as downloads (never executed or
 * rendered), so an uploaded file cannot run on the server.
 */
export interface Storage {
  put(data: Buffer): Promise<string>;
  get(key: string): Promise<Buffer>;
}

class LocalStorage implements Storage {
  constructor(private dir: string) {}
  async put(data: Buffer) {
    const key = `${new Date().toISOString().slice(0, 7)}/${crypto.randomUUID()}`;
    const file = path.join(this.dir, key);
    await fs.mkdir(path.dirname(file), { recursive: true, mode: 0o750 });
    await fs.writeFile(file, data, { mode: 0o640 });
    return key;
  }
  async get(key: string) {
    // Keys are generated by put(); reject anything that tries to leave the directory.
    if (!/^\d{4}-\d{2}\/[0-9a-f-]{36}$/.test(key)) throw new Error('invalid key');
    return fs.readFile(path.join(this.dir, key));
  }
}

class S3Storage implements Storage {
  private client = new S3Client({
    endpoint: config.s3.endpoint,
    region: config.s3.region,
    forcePathStyle: config.s3.forcePathStyle,
    credentials: config.s3.accessKeyId ? { accessKeyId: config.s3.accessKeyId, secretAccessKey: config.s3.secretAccessKey } : undefined,
  });
  async put(data: Buffer) {
    const key = `uploads/${new Date().toISOString().slice(0, 7)}/${crypto.randomUUID()}`;
    await this.client.send(new PutObjectCommand({ Bucket: config.s3.bucket, Key: key, Body: data, ContentType: 'application/octet-stream' }));
    return key;
  }
  async get(key: string) {
    const r = await this.client.send(new GetObjectCommand({ Bucket: config.s3.bucket, Key: key }));
    return Buffer.from(await r.Body!.transformToByteArray());
  }
}

export const storage: Storage | null =
  config.storage === 's3' ? new S3Storage() : config.storage === 'local' ? new LocalStorage(path.resolve(config.storageDir)) : null;
